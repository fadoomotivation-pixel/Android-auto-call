-- A demo company the founder can open in front of a builder.
--
-- Call Pro AI is sold to builder founders, and a founder decides in the first
-- two minutes of a demo. Until now the only data to show them was a real
-- customer's, which cannot be shown, or an empty company, which shows nothing.
--
-- This adds one made-up company, "Sunrise Infra (Demo data)", with 30 days of
-- believable work on it. The numbers are kept modest on purpose. A founder
-- trusts "the ad money comes back", not "everybody gets rich":
--
--     Meta ad spend     ₹1,00,000 in 30 days, three lead-form campaigns
--     Leads             600, all from those forms
--     Site visits       45 happened, 9 more booked for the coming week
--     Bookings          5 (3 won, 2 token paid)  →  ₹20,000 per booking
--     Saved             9 buyers reached a site visit only because Call Pro AI
--                       put them back in front of the telecaller (3 missed
--                       calls, a late follow-up, an unanswered WhatsApp)
--
-- WHAT IT ADDS
--   · companies.is_demo. True only for this company.
--   · demo_ad_spend. The demo's Meta numbers. Real spend is read live from
--     Meta and cannot be faked, so the demo carries its own, and the admin
--     shows it only inside the demo company, labelled "Demo data".
--   · demo_state + demo_refresh(). Every date here is relative to the day this
--     file is applied. demo_refresh() moves the whole company forward to
--     today, so "due today", "overdue" and "visit tomorrow" stay true on the
--     day of the demo. The admin's Demo account page calls it. Super admin
--     only, and it only ever touches a company whose is_demo is true.
--   · The company, three telecallers (one can sign in on the phone), three
--     projects, 600 leads, their calls, follow-ups, visits, visit outcomes,
--     lead history, objection → reply entries for the AI brain, and coach notes.
--
-- ISOLATION
--   Every row carries the demo company's id. Company admins never see it (RLS).
--   Phone numbers are +91 555xxxxxxx: not a mobile series, so a tap on Call in
--   the demo cannot ring a real person, and the phone's call sync (which only
--   uploads calls to numbers in the CRM) cannot pick up the founder's own calls.
--   recording_enabled and record_all_calls are off, the 7pm rep review is off,
--   no reps have a phone number, there are no Pulse subscribers, and there is no
--   facebook_integrations row, so the Meta CAPI trigger never fires for it.
--
-- RE-RUNNING
--   Safe. It first deletes every row whose company_id is the demo company (and
--   refuses to run if that id ever belongs to a company that is not a demo),
--   then writes the demo again. The three logins keep their ids, so a phone
--   that is signed in stays signed in.
--
-- WHY THE FOLLOW-UPS ARE "PARKED"
--   Inserting a follow-up stamps the lead's handled_at to now(), and putting
--   the real handled_at back fires close_followups_on_handled(), which closes
--   every pending follow-up that is already due. That would quietly close all
--   the overdue and due-today follow-ups the demo exists to show. So they are
--   written 100 years in the future, the lead clocks are restored, and then
--   they are moved back. demo_refresh() does the same.
--
-- Generated by supabase/demo/generate_demo_seed.py (deterministic). Only the
-- bcrypt hash of the phone login's password is in this file.
--
-- Not applied by this commit. The founder applies it by hand.
-- applied by hand on <date>

